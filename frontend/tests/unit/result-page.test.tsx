import { describe, it, expect, vi } from 'vitest'
import { render, screen } from '@testing-library/react'
import { MemoryRouter, Routes, Route } from 'react-router-dom'
import { TooltipProvider } from '@/components/ui/tooltip'
import { ResultPage } from '@/pages/result-page'

// Leaflet needs real element sizes that jsdom does not provide, so we stub the
// map. Everything else (answer, panels, trace, confidence, inputs) is the real
// component tree rendering real recorded fixture data.
vi.mock('@/components/result/result-map', () => ({
  ResultMap: () => <div data-testid="result-map" />,
}))

function renderResult(id: string) {
  return render(
    <TooltipProvider>
      <MemoryRouter initialEntries={[`/analysis/${id}`]}>
        <Routes>
          <Route path="/analysis/:id" element={<ResultPage />} />
        </Routes>
      </MemoryRouter>
    </TooltipProvider>,
  )
}

describe('ResultPage', () => {
  it('renders the land-cover result with answer, panel, trace, confidence and inputs', async () => {
    renderResult('SAT-2026-000101')

    // Answer (released, evidence sufficient).
    expect(await screen.findByText(/predominantly bare soil/i)).toBeInTheDocument()

    // Report id + a working link to the printable report.
    expect(screen.getByText('SAT-2026-000101')).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /view report/i })).toHaveAttribute(
      'href',
      '/analysis/SAT-2026-000101/report',
    )

    // The land-cover data panel with its measured metrics. ("Land-cover
    // analysis" appears as both the task badge and the panel title;
    // "Separability" as both a panel stat and a confidence factor.)
    expect(screen.getAllByText(/land-cover analysis/i).length).toBeGreaterThan(0)
    expect(screen.getAllByText(/separability/i).length).toBeGreaterThan(0)
    expect(screen.getByText('Land-cover distribution')).toBeInTheDocument()

    // Evidence-based confidence (not model-generated) with the real level.
    expect(screen.getByText('Confidence')).toBeInTheDocument()
    expect(screen.getByText(/not generated by a language model/i)).toBeInTheDocument()

    // Execution trace surfaces the tool pipeline, no chain-of-thought.
    expect(screen.getByText('Execution trace')).toBeInTheDocument()
    expect(screen.getAllByText('landcover-spectral-cv').length).toBeGreaterThan(0)
    expect(screen.getByText(/internal model reasoning is not shown/i)).toBeInTheDocument()

    // Inputs metadata + mocked map.
    expect(screen.getByText('Inputs')).toBeInTheDocument()
    expect(screen.getByTestId('result-map')).toBeInTheDocument()
  })

  it('shows the grounding count as not reportable instead of asserting a number (§28)', async () => {
    renderResult('SAT-2026-000103')

    // The released answer explains the extent is known but the count is not.
    expect(await screen.findByText(/built up extent is mapped/i)).toBeInTheDocument()

    // The grounding panel refuses to state an unreliable count. (The phrase
    // also appears in the released answer, so more than one match is expected.)
    expect(screen.getByText(/count not reportable/i)).toBeInTheDocument()
    expect(
      screen.getAllByText(/cannot be stated reliably from this image alone/i).length,
    ).toBeGreaterThan(0)

    // It still shows how the query was interpreted.
    expect(screen.getByText(/interpreted as/i)).toBeInTheDocument()
  })

  it('renders a friendly error for an unknown report id', async () => {
    renderResult('SAT-2026-999999')
    expect(await screen.findByText(/could not load this analysis/i)).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /back to dashboard/i })).toBeInTheDocument()
  })
})
